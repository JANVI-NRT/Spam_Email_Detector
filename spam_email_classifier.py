def evaluate(name, y_true, y_pred):
    TP = np.sum((y_true == 1) & (y_pred == 1))
    TN = np.sum((y_true == 0) & (y_pred == 0))
    FP = np.sum((y_true == 0) & (y_pred == 1))
    FN = np.sum((y_true == 1) & (y_pred == 0))

    accuracy = (TP + TN) / len(y_true)
    precision = TP / (TP + FP)
    recall = TP / (TP + FN)
    f1 = 2 * precision * recall / (precision + recall)

    print(name)
    print("Test Accuracy:", accuracy)
    print("Precision:", precision, " Recall:", recall, " F1:", f1)
    print("Confusion Matrix:\n", np.array([[TN, FP], [FN, TP]]))
    return accuracy

"""# Naive Bayes (Multinomial)"""

class NaiveBayes:

    def __init__(self, alpha=1):
        self.alpha = alpha

    def fit(self, X, y):
        self.prior = []
        self.likelihood = []

        for c in [0, 1]:
            Xc = X[y == c]
            self.prior.append(np.log(len(Xc) / len(X)))

            word_count = Xc.sum(axis=0) + self.alpha
            self.likelihood.append(np.log(word_count / word_count.sum()))

    def predict(self, X):
        preds = []
        for x in X:
            score0 = self.prior[0] + np.sum(x * self.likelihood[0])
            score1 = self.prior[1] + np.sum(x * self.likelihood[1])
            preds.append(1 if score1 > score0 else 0)
        return np.array(preds)

