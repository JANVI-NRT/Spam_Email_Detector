"""# Decision Tree (Entropy)"""

def entropy(y):
    c = np.bincount(y)
    p = c[c > 0] / len(y)
    return -np.sum(p * np.log2(p))

class DecisionTree:
    def fit(self, X, y, depth=0, max_depth=5):
        if depth == max_depth or len(set(y)) == 1:
            self.label = Counter(y).most_common(1)[0][0]
            return

        best_feat = -1
        best_gain = 0
        H = entropy(y)

        for f in range(X.shape[1]):
            thresh = np.mean(X[:, f])
            y_l = y[X[:, f] < thresh]
            y_r = y[X[:, f] >= thresh]

            if len(y_l) == 0 or len(y_r) == 0:
                continue

            gain = H - (len(y_l)/len(y))*entropy(y_l) - (len(y_r)/len(y))*entropy(y_r)

            if gain > best_gain:
                best_gain = gain
                best_feat = f
                best_thresh = thresh

        if best_feat == -1:
            self.label = Counter(y).most_common(1)[0][0]
            return

        self.f = best_feat
        self.th = best_thresh

        L = X[:, self.f] < self.th

        self.left = DecisionTree()
        self.left.fit(X[L], y[L], depth+1, max_depth)

        self.right = DecisionTree()
        self.right.fit(X[~L], y[~L], depth+1, max_depth)

    def predict_one(self, x):
        if hasattr(self, 'label'):
            return self.label
        if x[self.f] < self.th:
            return self.left.predict_one(x)
        return self.right.predict_one(x)

    def predict(self, X):
        preds = []
        for i in range(X.shape[0]):
            preds.append(self.predict_one(X[i]))
        return np.array(preds)

